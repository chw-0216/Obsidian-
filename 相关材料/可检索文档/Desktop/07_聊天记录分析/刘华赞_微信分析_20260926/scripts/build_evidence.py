# ---------- 3. 母亲会话中的相关提及（带上下文） ----------
KEY = ["华天雪", "赞赞", "刘华赞"]
with io.open(MOTHER_SRC, encoding="utf-8") as f:
    d = json.load(f)
msgs = d.get("messages") or []
hit_idx = [i for i, m in enumerate(msgs) if any(k in (m.get("content") or "") for k in KEY)]

extract, seen = [], set()
for i in hit_idx:
    lo, hi = max(0, i - 5), min(len(msgs), i + 6)
    for j in range(lo, hi):
        if j in seen:
            continue
        seen.add(j)
        m = msgs[j]
        who = "我" if m.get("isSend") == 1 else "母亲刘丽萍"
        rec = {
            "时间": fmt(m["createTime"]),
            "发言": who,
            "内容": (m.get("content") or "").replace("\n", " ")[:400],
            "命中": "★" if any(k in (m.get("content") or "") for k in KEY) else "",
        }
        extract.append(rec)

