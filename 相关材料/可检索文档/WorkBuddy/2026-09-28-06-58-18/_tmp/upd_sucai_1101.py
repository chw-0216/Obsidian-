def check_table(lines, label):
    bad = []
    cur = None
    for idx, ln in enumerate(lines):
        if ln.startswith("|"):
            n = ln.count("|")
            if cur is None:
                cur = n
            elif n != cur:
                bad.append((idx + 1, n, cur, ln[:50]))
        else:
            cur = None
    if bad:
        print("COLS-FAIL", label, bad[:6])
    else:
        print("COLS-OK", label)

